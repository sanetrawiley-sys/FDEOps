#!/usr/bin/env node
// Generated packages are independent installations, not independently authored methods.
const fs = require('node:fs')
const path = require('node:path')
const catalog = require('./skill-catalog')
const root = path.resolve(__dirname, '..')
const source = path.join(root, 'skills/fde/references')

function referencesFor(method, referenceRoot = source) {
  const known = new Set(fs.readdirSync(referenceRoot).filter(f => f.endsWith('.md')))
  const pending = [`${method}.md`, 'task-context.md']
  const found = new Set()
  while (pending.length) {
    const file = pending.pop()
    if (found.has(file)) continue
    if (!known.has(file)) throw new Error(`Missing canonical reference: ${file}`)
    found.add(file)
    const body = fs.readFileSync(path.join(referenceRoot, file), 'utf8')
    // Includes plain/backticked method links in older references as well as Markdown links.
    for (const match of body.matchAll(/(?<![\w-])([a-z][a-z-]*\.md)\b/g)) {
      if (known.has(match[1]) && !found.has(match[1])) pending.push(match[1])
    }
    for (const match of body.matchAll(/\]\(([^)]+\.md)(?:#[^)]*)?\)/g)) {
      if (/^(?:https?:|#)/.test(match[1])) continue
      const target = path.resolve(referenceRoot, match[1])
      if (path.dirname(target) !== referenceRoot || !known.has(path.basename(target))) {
        throw new Error(`Nonportable instruction link in ${file}: ${match[1]}`)
      }
    }
  }
  return [...found].sort()
}
function entrypoint(item) {
  return `---\nname: ${item.name}\ndescription: ${item.description}\n---\n\n# ${item.name}\n\n<!-- Generated by bin/generate-skills.js; edit the canonical references and catalog. -->\n\n## Purpose\n\n${item.description}\n\nRead [the task context contract](references/task-context.md), then [the method](references/${item.method}.md). Load further references only when the task needs them. Everything linked is included in this skill; no other skill pack is required.\n\n## Principles\n\n- Work directly from the supplied permitted context. Standalone work does not require an engagement folder or initialization. Record filenames in the method are optional persistence destinations when no engagement is bound.\n- If called by @fde, reuse its current sanitized packet and scope. Do not restart setup, discovery or questions already answered.\n- The task context contract controls persistence and authority in both modes. Preserve unknowns and distinguish implementation, verification, deployment and acceptance.\n- Use the customer's repository instructions and available tools. Report a missing capability or unrun check honestly; do not claim that installing a skill provisions infrastructure.\n`
}
function expectedFiles(item, referenceRoot = source) {
  const files = new Map([['SKILL.md', entrypoint(item)]])
  for (const ref of referencesFor(item.method, referenceRoot)) files.set(`references/${ref}`, fs.readFileSync(path.join(referenceRoot, ref), 'utf8'))
  return files
}
function walk(dir, prefix = '') {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    if (e.isSymbolicLink()) throw new Error(`Unexpected symlink: ${path.join(dir, e.name)}`)
    const rel = prefix + e.name
    return e.isDirectory() ? walk(path.join(dir, e.name), rel + '/') : [rel]
  })
}
function generate(check = false) {
  const errors = []
  for (const item of catalog) {
    const dest = path.join(root, 'skills', item.name)
    const expected = expectedFiles(item)
    for (const rel of walk(dest)) if (!expected.has(rel)) errors.push(`Unexpected generated file: ${item.name}/${rel}`)
    for (const [rel, body] of expected) {
      const target = path.join(dest, rel)
      if (check) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) errors.push(`Stale generated skill: ${item.name}/${rel}`)
      } else {
        fs.mkdirSync(path.dirname(target), { recursive: true })
        fs.writeFileSync(target, body)
      }
    }
  }
  if (errors.length) throw new Error(errors.join('\n'))
}
module.exports = { referencesFor, expectedFiles, generate }
if (require.main === module) {
  try { generate(process.argv.includes('--check')); console.log('Skill packages match canonical methods.') }
  catch (error) { console.error(error.message); process.exitCode = 1 }
}
